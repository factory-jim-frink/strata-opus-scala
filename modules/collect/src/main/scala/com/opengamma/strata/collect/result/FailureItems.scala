/**
 * A list of failure items.
 *
 * This provides a wrapper around a list of `FailureItem`.
 *
 * This could be used with `Pair` to create an object that handles partial success/failure,
 * such as `Pair<List<String>, FailureItems>`.
 * However, from v1.1.1 `ValueWithFailures` captures that use case better.
 *
 * @constructor Creates an instance.
 * @param rawFailures  the value of the property, not null
 */
@BeanDefinition(builderScope = "private", constructorScope = "package")
@SerialVersionUID(1L)
final class FailureItems private[result] (
    rawFailures: List[FailureItem])
  extends ImmutableBean with Serializable {

  JodaBeanUtils.notNull(rawFailures, "failures")
  /**
   * The failures.
   */
  @(PropertyDefinition @field)(validate = "notNull")
  private val failures: ImmutableList[FailureItem] = ImmutableList.copyOf(rawFailures)

  //-------------------------------------------------------------------------
  /**
   * Combines these failure items with other failure items.
   *
   * @param other the other failure items
   * @return the combined failure items
   */
  def combinedWith(other: FailureItems): FailureItems = {
    combinedWith(other.failures: List[FailureItem])
  }

  /**
   * Combines these failure items with other failure items.
   *
   * @param otherFailures the other failure items
   * @return the combined failure items
   */
  @varargs
  def combinedWith(otherFailures: FailureItem*): FailureItems = {
    combinedWith(ImmutableList.copyOf(otherFailures.toArray): List[FailureItem])
  }

  /**
   * Combines these failure items with other failure items.
   *
   * @param otherFailures the other failure items
   * @return the combined failure items
   */
  def combinedWith(otherFailures: List[FailureItem]): FailureItems = {
    FailureItems.builder().addAllFailures(failures).addAllFailures(otherFailures).build()
  }

  //-------------------------------------------------------------------------
  /**
   * Checks if the list of failures is empty.
   *
   * @return true if there are no failures
   */
  def isEmpty(): Boolean = {
    failures.isEmpty()
  }

  //-------------------------------------------------------------------------
  /**
   * Returns a string summary of the failures, as a single line excluding the stack traces.
   *
   * @return the summary string
   */
  override def toString(): String = {
    failures.stream()
        .map[String](f => f.toString())
        .collect(Collectors.joining(", ", "FailureItems[", "]"))
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): FailureItems.Meta = {
