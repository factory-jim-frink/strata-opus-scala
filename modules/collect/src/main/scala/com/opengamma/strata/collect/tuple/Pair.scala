    ComparisonChain.start()
        .compare(first.asInstanceOf[Comparable[?]], other.first.asInstanceOf[Comparable[?]])
        .compare(second.asInstanceOf[Comparable[?]], other.second.asInstanceOf[Comparable[?]])
