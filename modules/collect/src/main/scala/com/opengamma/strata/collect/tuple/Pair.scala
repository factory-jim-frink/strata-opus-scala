  }

  /**
   * Gets the pair using a standard string format.
   *
   * The standard format is '[\$first, \$second]'. Spaces around the values are trimmed.
   *
   * @return the pair as a string
   */
  override def toString(): String = {
    new java.lang.StringBuilder()
        .append('[')
        .append(first)
        .append(", ")
        .append(second)
        .append(']')
        .toString()
  }

