  /**
   * Combines this instance with another.
   *
   * @tparam C  the type of the first value in the other instance
   * @tparam D  the type of the second value in the other instance
   * @param other  the other pair
   * @param combinerFirst  the combiner of first values
   * @param combinerSecond  the combiner of second values
   * @return the combined pair instance
   */
  def combinedWith[C, D](
      other: Pair[C, D],
      combinerFirst: BiFunction[? >: A, ? >: C, ? <: A],
      combinerSecond: BiFunction[? >: B, ? >: D, ? <: B]): Pair[A, B] = {

    Pair.of[A, B](combinerFirst.apply(first, other.getFirst()), combinerSecond.apply(second, other.getSecond()))
  }

