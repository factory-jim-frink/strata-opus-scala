    // this method is retained to ensure binary compatibility
    Failure.of(FailureItem.of(reason, cause, message, messageArgs*))
  }

  /**
   * Obtains a failure from a reason and throwable.
   *
   * @param reason  the reason
   * @param cause  the cause
   * @return the failure
   */
  def of(reason: FailureReason, cause: Throwable): Failure = {
    Failure.of(FailureItem.of(reason, cause))
  }

  /**
   * Obtains a failure from a reason and exception.
   *
   * @param reason  the reason
   * @param cause  the cause
   * @return the failure
   */
  def of(reason: FailureReason, cause: Exception): Failure = {
    // this method is retained to ensure binary compatibility
    Failure.of(FailureItem.of(reason, cause))
  }

  /**
   * Obtains a failure for a single failure item.
   *
   * @param item  the failure item
   * @return the failure
   */
  def of(item: FailureItem): Failure = {
    new Failure(item.getReason(), item.getMessage(), ImmutableSet.of[FailureItem](item))
  }

  /**
   * Obtains a failure for multiple failure items.
   *
   * @param item  the first failure item
   * @param additionalItems  additional failure items
   * @return the failure
   */
  @varargs
  def of(item: FailureItem, additionalItems: FailureItem*): Failure = {
    of(ImmutableSet.builder[FailureItem]().add(item).add(additionalItems*).build(): Collection[FailureItem])
  }

  /**
   * Obtains a failure for a non-empty collection of failure items.
   *
   * @param items  the failures, not empty
   * @return the failure
   */
  def of(items: Collection[FailureItem]): Failure = {
    ArgChecker.notEmpty(items, "items")
    val itemSet: Set[FailureItem] = ImmutableSet.copyOf(items)
    val message = itemSet.stream()
        .map[String](item => item.getMessage())
        .collect(Collectors.joining(", "))
    val combiner: BinaryOperator[FailureReason] = (s1, s2) => if (s1 eq s2) s1 else FailureReason.MULTIPLE
    val reason = itemSet.stream()
        .map[FailureReason](item => item.getReason())
        .reduce(combiner).get()
    new Failure(reason, message, itemSet)
  }

  /**
   * Creates a failure from the throwable.
   *
   * This recognizes `FailureException` and `FailureItemProvider`.
   *
   * @param th  the throwable to be processed
   * @return the failure
   */
  def from(th: Throwable): Failure = {
    try {
      throw th
    } catch {
      case ex: FailureException =>
        ex.getFailure()
      case ex: Throwable =>
        if (ex.isInstanceOf[FailureItemProvider]) {
          of(ex.asInstanceOf[FailureItemProvider].getFailureItem())
        } else {
          of(FailureReason.ERROR, ex)
        }
    }
  }

