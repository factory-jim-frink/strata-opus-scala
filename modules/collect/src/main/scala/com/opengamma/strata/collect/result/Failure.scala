   * @param reason  the reason
   * @param cause  the cause
   * @param message  the failure message, possibly containing placeholders, formatted using `Messages.format`
   * @param messageArgs  arguments used to create the failure message
   * @return the failure
   */
  @varargs
  def of(reason: FailureReason, cause: Throwable, message: String, messageArgs: Object*): Failure = {
    Failure.of(FailureItem.of(reason, cause, message, messageArgs*))
  }

  /**
