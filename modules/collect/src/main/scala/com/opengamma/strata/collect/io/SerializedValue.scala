package com.opengamma.strata.collect.io

import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.io.ObjectInputStream
import java.io.ObjectOutputStream
import java.io.Serializable
import java.io.UncheckedIOException
import java.lang.StringBuilder
import java.lang.invoke.MethodHandles

import scala.annotation.meta.field
import scala.annotation.static

import org.joda.beans.Bean
import org.joda.beans.ImmutableBean
import org.joda.beans.JodaBeanUtils
import org.joda.beans.MetaBean
import org.joda.beans.TypedMetaBean
import org.joda.beans.gen.BeanDefinition
import org.joda.beans.gen.ImmutableValidator
import org.joda.beans.gen.PropertyDefinition
import org.joda.beans.impl.light.LightMetaBean
import org.joda.beans.ser.JodaBeanSer
import org.joda.beans.ser.SerDeserializers

import com.opengamma.strata.collect.UncheckedReflectiveOperationException

/**
 * A serialized value.
 *
 * This bean allows a Java object to be passed around in serialized form.
 * The object can be a Joda-Convert type, a Joda-Bean or implement `Serializable`.
 * This is useful where an object needs to be transported to another Java process where
 * the object's class may not be on the classpath.
 */
@BeanDefinition(style = "light")
final class SerializedValue private (
    /**
     * The value, as a serialized Joda-Convert string.
     */
    @(PropertyDefinition @field)(get = "field")
    private val convert: String,
    rawBean: Array[Byte],
    rawJava: Array[Byte])
  extends ImmutableBean {

  /**
   * The value, as a serialized Joda-Bean.
   */
  @(PropertyDefinition @field)(get = "field")
  private val bean: Array[Byte] = (if (rawBean != null) rawBean.clone() else null)
  /**
   * The value, serialized by Java serialization.
   */
  @(PropertyDefinition @field)(get = "field")
  private val java: Array[Byte] = (if (rawJava != null) rawJava.clone() else null)

  validate()

  //-------------------------------------------------------------------------
  @ImmutableValidator
  private def validate(): Unit = {
    val count = (if (convert != null) 1 else 0) + (if (bean != null) 1 else 0) + (if (java != null) 1 else 0)
    if (count > 1) {
      throw new IllegalArgumentException("Value must be present in one form only")
    }
  }

  //-------------------------------------------------------------------------
  /**
   * Deserializes the value.
   *
   * This converts the value from the underlying string or binary form.
   * As such, it might throw an exception.
   * The intention is that deserialization uses the same Java type as serialization.
   *
   * @tparam T the type of the value
   * @param javaType the declared Java type
   * @return the value, null if the serialized value represents null
   * @throws java.lang.RuntimeException if the value cannot be deserialized
   */
  def deserialize[T](javaType: Class[T]): T = {
    if (convert != null) {
      JodaBeanUtils.stringConverter().convertFromString(javaType, convert)
    } else if (bean != null) {
      JodaBeanSer.COMPACT.withDeserializers(SerDeserializers.LENIENT).binReader().read(bean, javaType)
    } else if (java != null) {
      try {
        closing(new ByteArrayInputStream(java)) { bais =>
          closing(new ObjectInputStream(bais)) { ois =>
            javaType.cast(ois.readObject())
          }
        }
      } catch {
        case ex: IOException => throw new UncheckedIOException(ex)
        case ex: ClassNotFoundException => throw new UncheckedReflectiveOperationException(ex)
      }
    } else {
      null.asInstanceOf[T]
    }
  }

  // equivalent of try-with-resources, adding any close failure as suppressed to the primary failure
  private def closing[R <: AutoCloseable, A](resource: R)(body: R => A): A = {
    var primary: Throwable = null
    try {
      body(resource)
    } catch {
      case ex: Throwable =>
        primary = ex
        throw ex
    } finally {
      if (resource != null) {
        if (primary != null) {
          try {
            resource.close()
          } catch {
            case closeEx: Throwable => primary.addSuppressed(closeEx)
          }
        } else {
          resource.close()
        }
      }
    }
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): TypedMetaBean[SerializedValue] = {
    SerializedValue.META_BEAN
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else if (obj != null && (obj.getClass() eq this.getClass())) {
      val other = obj.asInstanceOf[SerializedValue]
      JodaBeanUtils.equal(convert, other.convert) &&
          JodaBeanUtils.equal(bean, other.bean) &&
          JodaBeanUtils.equal(java, other.java)
    } else {
      false
    }
  }

  override def hashCode(): Int = {
    var hash = getClass().hashCode()
    hash = hash * 31 + JodaBeanUtils.hashCode(convert)
    hash = hash * 31 + JodaBeanUtils.hashCode(bean)
    hash = hash * 31 + JodaBeanUtils.hashCode(java)
    hash
  }

  override def toString(): String = {
    val buf = new StringBuilder(128)
    buf.append("SerializedValue{")
    buf.append("convert").append('=').append(JodaBeanUtils.toString(convert)).append(',').append(' ')
    buf.append("bean").append('=').append(JodaBeanUtils.toString(bean)).append(',').append(' ')
    buf.append("java").append('=').append(JodaBeanUtils.toString(java))
    buf.append('}')
    buf.toString()
  }

  //-------------------------- AUTOGENERATED END --------------------------
}

object SerializedValue {

  /**
   * The meta-bean for `SerializedValue`.
   */
  // initialized in the class static initializer, so the lookup has private access to the bean class
  @static private[io] val META_BEAN: TypedMetaBean[SerializedValue] =
    LightMetaBean.of(
        classOf[SerializedValue],
        MethodHandles.lookup(),
        Array[String](
            "convert",
            "bean",
            "java"),
        new Array[Object](0)*)

  @static private val REGISTERED: Boolean = {
    MetaBean.register(META_BEAN)
    true
  }

  //-------------------------------------------------------------------------
  /**
   * Obtains an instance by serializing the value based on the declared Java type.
   *
   * The declared Java type is not necessarily the same as the actual type of the value.
   * For example, the declared type might be an interface and the actual type the implementation class.
   *
   * @tparam T the type of the value
   * @param javaType the declared Java type
   * @param value the value, may be null, a Joda-Convert type, Joda-Bean, or Serializable
   * @return the value object
   * @throws java.lang.RuntimeException if the value cannot be stored
   */
  def serialize[T](javaType: Class[T], value: T): SerializedValue = {
    val obj: Object = value.asInstanceOf[Object]
    if (obj == null) {
      new SerializedValue(null, null, null)
    } else if (JodaBeanUtils.stringConverter().isConvertible(javaType)) {
      val str = JodaBeanUtils.stringConverter().convertToString(javaType, obj)
      new SerializedValue(str, null, null)
    } else {
      obj match {
        case beanValue: Bean =>
          val bytes = JodaBeanSer.COMPACT.binWriter().write(beanValue, false)
          new SerializedValue(null, bytes, null)
        case _: Serializable =>
          try {
            closing(new ByteArrayOutputStream()) { baos =>
              closing(new ObjectOutputStream(baos)) { oos =>
                oos.writeObject(obj)
                oos.flush()
              }
              new SerializedValue(null, null, baos.toByteArray())
            }
          } catch {
            case ex: IOException => throw new UncheckedIOException(ex)
          }
        case _ =>
          throw new IllegalArgumentException("Value must be a Joda-Convert type, Joda-Bean or Serializable")
      }
    }
  }

  /**
   * The meta-bean for `SerializedValue`.
   * @return the meta-bean, not null
   */
  def meta(): TypedMetaBean[SerializedValue] = {
    META_BEAN
  }

  // equivalent of try-with-resources, adding any close failure as suppressed to the primary failure
  private def closing[R <: AutoCloseable, A](resource: R)(body: R => A): A = {
    var primary: Throwable = null
    try {
      body(resource)
    } catch {
      case ex: Throwable =>
        primary = ex
        throw ex
    } finally {
      if (resource != null) {
        if (primary != null) {
          try {
            resource.close()
          } catch {
            case closeEx: Throwable => primary.addSuppressed(closeEx)
          }
        } else {
          resource.close()
        }
      }
    }
  }

}
