/**
 * A value and its derivatives.
 *
 * This defines a standard way to return a value and its derivatives to certain inputs.
 * It is in particular used as a return object for Algorithmic Differentiation versions of some functions.
 */
@BeanDefinition(style = "light")
@SerialVersionUID(1L)
final class ValueDerivatives private (
    /**
     * The value of the variable.
     */
    @(PropertyDefinition @field)
    private val value: Double,
    /**
     * The derivatives of the variable with respect to some inputs.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val derivatives: DoubleArray)
  extends ImmutableBean with Serializable {

  JodaBeanUtils.notNull(derivatives, "derivatives")

  //-------------------------------------------------------------------------
  /**
   * Gets the derivative of the variable with respect to an input.
   *
   * @param index  the zero-based derivative to obtain
   * @return the derivative
   * @throws java.lang.IndexOutOfBoundsException if the index is invalid
   */
  def getDerivative(index: Int): Double = {
    derivatives.get(index)
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): TypedMetaBean[ValueDerivatives] = {
    ValueDerivatives.META_BEAN
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the value of the variable.
   * @return the value of the property
   */
  def getValue(): Double = {
    value
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the derivatives of the variable with respect to some inputs.
   * @return the value of the property, not null
   */
  def getDerivatives(): DoubleArray = {
    derivatives
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else if (obj != null && (obj.getClass() eq this.getClass())) {
      val other = obj.asInstanceOf[ValueDerivatives]
      JodaBeanUtils.equal(value, other.value) &&
          JodaBeanUtils.equal(derivatives, other.derivatives)
    } else {
      false
    }
  }

  override def hashCode(): Int = {
    var hash = getClass().hashCode()
    hash = hash * 31 + JodaBeanUtils.hashCode(value)
    hash = hash * 31 + JodaBeanUtils.hashCode(derivatives)
    hash
  }

  override def toString(): String = {
    val buf = new java.lang.StringBuilder(96)
    buf.append("ValueDerivatives{")
    buf.append("value").append('=').append(JodaBeanUtils.toString(java.lang.Double.valueOf(value))).append(',').append(' ')
    buf.append("derivatives").append('=').append(JodaBeanUtils.toString(derivatives))
    buf.append('}')
    buf.toString()
  }

  //-------------------------- AUTOGENERATED END --------------------------
}

