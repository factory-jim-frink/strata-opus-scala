   * @param rateProvider  the provider of FX rates
   * @return the converted instance, in the specified currency
   * @throws java.lang.RuntimeException if no FX rate could be found
   */
  override def convertedTo(resultCurrency: Currency, rateProvider: FxRateProvider): Payment = {
    if (getCurrency().equals(resultCurrency)) {
      this
    } else {
      Payment.of(value.convertedTo(resultCurrency, rateProvider), date)
    }
  }

