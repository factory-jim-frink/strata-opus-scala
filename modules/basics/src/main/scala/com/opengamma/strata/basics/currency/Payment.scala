   *
   * @return the amount of the payment
   */
  def getAmount(): Double = {
    value.getAmount()
  }

  //-------------------------------------------------------------------------
  /**
   * Adjusts the payment date using the rules of the specified adjuster.
   *
   * The adjuster is typically an instance of `BusinessDayAdjustment`.
   * If the date is unchanged by the adjuster, `this` payment will be returned.
   *
   * @param adjuster  the adjuster to apply to the payment date
   * @return the adjusted payment
   */
  def adjustDate(adjuster: TemporalAdjuster): Payment = {
    val adjusted = date.`with`(adjuster)
    if (adjusted.equals(date)) this else toBuilder().date(adjusted).build()
  }

  //-------------------------------------------------------------------------
  /**
   * Returns a copy of this `Payment` with the value negated.
   *
   * This takes this payment and negates it.
   *
   * This instance is immutable and unaffected by this method.
   *
   * @return a payment based on this with the value negated
   */
  def negated(): Payment = {
    Payment.of(value.negated(), date)
  }

  /**
