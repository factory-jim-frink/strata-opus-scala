   * Obtains an instance from a map of reference data.
   *
   * Each entry in the map is a single piece of reference data, keyed by the matching identifier.
   * For example, a `HolidayCalendarId` associated with a `HolidayCalendar`.
   * The caller must ensure that the each entry in the map corresponds with the parameterized
   * type on the identifier.
   *
   * The resulting `ImmutableReferenceData` instance does not include the
   * minimal set of reference data that is essential for pricing.
   * To include the minimal set, use `ReferenceData#of(Map)` or `combinedWith(ReferenceData)`.
   *
   * @param values  the reference data values
   * @return the reference data instance
   * @throws java.lang.ClassCastException if a value does not match the parameterized type associated with the identifier
   */
  // @static because the inherited static ReferenceData.of suppresses the static forwarder
  @static def of(values: Map[? <: ReferenceDataId[?], ?]): ImmutableReferenceData = {
    // validation handles case where value does not match identifier
    val validator: BiConsumer[ReferenceDataId[?], Any] = (id, value) => validateEntry(id, value.asInstanceOf[Object])
    values.forEach(validator)
    new ImmutableReferenceData(values)
  }

  /**
   * Obtains an instance from a single reference data entry.
   *
   * This returns an instance containing a single entry based on the specified identifier and value.
   * This is primarily of interest to test cases.
   *
   * The resulting `ImmutableReferenceData` instance does not include the
   * minimal set of reference data that is essential for pricing.
   *
   * @tparam T  the type of the reference data
   * @param id  the identifier
   * @param value  the reference data values
   * @return the reference data instance
   * @throws java.lang.ClassCastException if a value does not match the parameterized type associated with the identifier
   */
  @static def of[T](id: ReferenceDataId[T], value: T): ImmutableReferenceData = {
    // validation handles edge case where input by raw or polluted types
    validateEntry(id, value.asInstanceOf[Object])
    new ImmutableReferenceData(ImmutableMap.of[ReferenceDataId[?], Object](id, value.asInstanceOf[Object]))
  }

  // validates a single entry
  @static private def validateEntry(id: ReferenceDataId[?], value: Object): Unit = {
    if (!id.getReferenceDataType().isInstance(value)) {
      if (value == null) {
        throw new IllegalArgumentException(Messages.format(
            "Value for identifier '{}' must not be null", id))
      }
      throw new ClassCastException(Messages.format(
          "Value for identifier '{}' does not implement expected type '{}': '{}'",
          id, id.getReferenceDataType().getSimpleName(), value))
    }
  }

  /**
   * Obtains an instance containing no reference data.
   *
   * @return empty reference data
   */
  // @static because the inherited static ReferenceData.empty suppresses the static forwarder
  @static def empty(): ImmutableReferenceData = {
    EMPTY
  }

