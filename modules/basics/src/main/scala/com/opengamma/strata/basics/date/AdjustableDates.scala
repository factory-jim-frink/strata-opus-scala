/**
 * An adjustable list of dates.
 *
 * This class combines a list of unadjusted dates with the single business day adjustment necessary to adjust them.
 * Calling the `adjusted(ReferenceData)` method will return the adjusted dates.
 */
@BeanDefinition(builderScope = "private")
@SerialVersionUID(1L)
final class AdjustableDates private (
    /**
     * The unadjusted dates, in order.
     *
     * These dates may be non-business days.
     * The business day adjustment is used to ensure each date is a valid business day.
     */
    @(PropertyDefinition @field)(validate = "notEmpty")
    private val unadjusted: ImmutableList[LocalDate],
    /**
     * The business day adjustment that is to be applied to the unadjusted dates.
     *
     * This is used to adjust each date if it is not a business day.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val adjustment: BusinessDayAdjustment)
  extends ImmutableBean with Serializable {

  // the unadjusted list is checked for emptiness and copied by AdjustableDates.copyNotEmpty
  JodaBeanUtils.notNull(adjustment, "adjustment")
  validate()

  //-------------------------------------------------------------------------
  @ImmutableValidator
  private def validate(): Unit = {
    ArgChecker.isTrue(
        Ordering.natural[LocalDate]().isStrictlyOrdered(unadjusted),
        "Dates must be in order and without duplicates")
  }

  //-------------------------------------------------------------------------
  /**
   * Adjusts the dates using the business day adjustment.
   *
   * This returns the adjusted dates, calculated by applying the business day
   * adjustment to each unadjusted date. Duplicates are removed.
   *
   * @param refData  the reference data to use
   * @return the adjusted dates
   */
  def adjusted(refData: ReferenceData): ImmutableList[LocalDate] = {
    val adjuster = adjustment.resolve(refData)
    unadjusted.stream()
        .map[LocalDate](date => adjuster.adjust(date))
        .distinct()
        .collect(Guavate.toImmutableList[LocalDate]())
  }

  //-------------------------------------------------------------------------
  /**
   * Returns a list of `AdjustableDate` equivalent to this instance.
   *
   * @return the adjusted date
   */
  def toAdjustableDateList(): ImmutableList[AdjustableDate] = {
    unadjusted.stream()
        .map[AdjustableDate](date => AdjustableDate.of(date, adjustment))
        .collect(Guavate.toImmutableList[AdjustableDate]())
  }

  //-------------------------------------------------------------------------
  /**
   * Returns a string describing the adjustable dates.
   *
   * @return the descriptive string
   */
  override def toString(): String = {
    if (adjustment.equals(BusinessDayAdjustment.NONE)) {
      unadjusted.toString()
    } else {
      new java.lang.StringBuilder(64)
          .append(unadjusted)
          .append(" adjusted by ")
          .append(adjustment).toString()
    }
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): AdjustableDates.Meta = {
    AdjustableDates.Meta.INSTANCE
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the unadjusted dates, in order.
   *
   * These dates may be non-business days.
   * The business day adjustment is used to ensure each date is a valid business day.
   * @return the value of the property, not empty
   */
  def getUnadjusted(): ImmutableList[LocalDate] = {
    unadjusted
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the business day adjustment that is to be applied to the unadjusted dates.
   *
   * This is used to adjust each date if it is not a business day.
   * @return the value of the property, not null
   */
  def getAdjustment(): BusinessDayAdjustment = {
    adjustment
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else if (obj != null && (obj.getClass() eq this.getClass())) {
      val other = obj.asInstanceOf[AdjustableDates]
      JodaBeanUtils.equal(unadjusted, other.unadjusted) &&
          JodaBeanUtils.equal(adjustment, other.adjustment)
    } else {
      false
    }
  }

  override def hashCode(): Int = {
    var hash = getClass().hashCode()
    hash = hash * 31 + JodaBeanUtils.hashCode(unadjusted)
    hash = hash * 31 + JodaBeanUtils.hashCode(adjustment)
    hash
  }

  //-------------------------- AUTOGENERATED END --------------------------
}

