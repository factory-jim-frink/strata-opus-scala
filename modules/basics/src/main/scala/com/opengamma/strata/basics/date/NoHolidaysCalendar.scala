  //-------------------------------------------------------------------------
  override def getId(): HolidayCalendarId = {
    HolidayCalendarIds.NO_HOLIDAYS
  }

  override def isHoliday(date: LocalDate): Boolean = {
    false
  }

  override def isBusinessDay(date: LocalDate): Boolean = {
    true
  }

  override def shift(date: LocalDate, amount: Int): LocalDate = {
    LocalDateUtils.plusDays(date, amount)
  }

  override def next(date: LocalDate): LocalDate = {
    LocalDateUtils.plusDays(date, 1)
  }

  override def nextOrSame(date: LocalDate): LocalDate = {
    ArgChecker.notNull(date, "date")
  }

  override def previous(date: LocalDate): LocalDate = {
    LocalDateUtils.plusDays(date, -1)
  }

  override def previousOrSame(date: LocalDate): LocalDate = {
    ArgChecker.notNull(date, "date")
  }

  override def nextSameOrLastInMonth(date: LocalDate): LocalDate = {
    ArgChecker.notNull(date, "date")
  }

  override def daysBetween(startInclusive: LocalDate, endExclusive: LocalDate): Int = {
    Math.toIntExact(LocalDateUtils.daysBetween(startInclusive, endExclusive))
  }

  override def combinedWith(other: HolidayCalendar): HolidayCalendar = {
    ArgChecker.notNull(other, "other")
  }

  //-------------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    obj.isInstanceOf[NoHolidaysCalendar]
  }

  override def hashCode(): Int = {
    1
  }

  override def toString(): String = {
    "HolidayCalendar[NoHolidays]"
  }

