/**
 * A holiday calendar implementation that has no holidays.
 *
 * This immutable implementation of `HolidayCalendar` treats all days as valid business days.
 */
@BeanDefinition(builderScope = "private")
@SerialVersionUID(1L)
final class NoHolidaysCalendar private ()
  extends HolidayCalendar with ImmutableBean with Serializable {
  // methods are overridden from default implementations to gain performance

  // resolve after deserialization
  private def readResolve(): Object = {
    NoHolidaysCalendar.INSTANCE
