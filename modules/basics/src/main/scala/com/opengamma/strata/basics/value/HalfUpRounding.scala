/**
 * Standard implementation of `Rounding` that uses the half-up convention.
 *
 * This class implements `Rounding` to provide the ability to round a number.
 * Rounding follows the normal `RoundingMode#HALF_UP` convention.
 * For example, this could be used to round a price to the appropriate market convention.
 *
 * Note that rounding a `double` is not straightforward as floating point
 * numbers are based on a binary representation, not a decimal one.
 * For example, the value 0.1 cannot be exactly represented in a `double`.
 */
@BeanDefinition(builderScope = "private")
@SerialVersionUID(1L)
private[value] final class HalfUpRounding @ImmutableConstructor private (
    rawDecimalPlaces: Int,
    rawFraction: Int)
  extends Rounding with ImmutableBean with Serializable {

  if (rawDecimalPlaces < 0 || rawDecimalPlaces > 255) {
    throw new IllegalArgumentException("Invalid decimal places, must be from 0 to 255 inclusive")
  }
  if (rawFraction < 0 || rawFraction > 256) {
    throw new IllegalArgumentException("Invalid fraction, must be from 0 to 256 inclusive")
  }
  /**
   * The number of decimal places to round to.
   *
   * Rounding follows the normal `RoundingMode#HALF_UP` convention.
   *
   * The value must be from 0 to 255 inclusive.
   */
  @(PropertyDefinition @field)
  private val decimalPlaces: Int = ArgChecker.notNegative(rawDecimalPlaces, "decimalPlaces")
  /**
   * The fraction of the smallest decimal place to round to.
   *
   * If used, this allows the rounding point to be set as a fraction of the smallest decimal place.
   * For example, setting this field to 32 will round to the nearest 1/32nd of the last decimal place.
   *
   * This will not be present if rounding is to an exact number of decimal places and there is no fraction.
   * The value must be from 2 to 256 inclusive, 0 is used to indicate no fractional part.
   */
  @(PropertyDefinition @field)
  private val fraction: Int = if (rawFraction <= 1) 0 else rawFraction
  /**
   * The fraction, as a `BigDecimal`.
   * Not a Joda-Beans property.
   */
  @transient
  private val fractionDecimal: BigDecimal = if (rawFraction <= 1) null else BigDecimal.valueOf(this.fraction.toLong)
  /**
   * The hash code.
   * Uniquely identifies the state of the object.
   * Not a Joda-Beans property.
   */
  @transient
  private val uniqueHashCode: Int = (this.decimalPlaces << 16) + this.fraction

  // deserialize transient
  @throws[ObjectStreamException]
  private def readResolve(): Object = {
    new HalfUpRounding(decimalPlaces, fraction)
  }

  //-------------------------------------------------------------------------
  override def round(value: Double): Double = {
    super.round(value)
  }

  override def round(value: BigDecimal): BigDecimal = {
    if (fraction > 1) {
      value
          .multiply(fractionDecimal)
          .setScale(decimalPlaces, RoundingMode.HALF_UP)
          .divide(fractionDecimal)
    } else {
      value.setScale(decimalPlaces, RoundingMode.HALF_UP)
    }
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
