          uniqueHashCode == other.uniqueHashCode
        case _ =>
          false
      }
    }
  }

  override def hashCode(): Int = {
    uniqueHashCode
  }

  //-------------------------------------------------------------------------
  override def toString(): String = {
    "Round to " + (if (fraction > 1) "1/" + fraction + " of " else "") + decimalPlaces + "dp"
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): HalfUpRounding.Meta = {
    HalfUpRounding.Meta.INSTANCE
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the number of decimal places to round to.
