        val weekendDow = weekendIt.next()
        val daysDiff = weekendDow.getValue() - firstOfMonth.getDayOfWeek().getValue()
        val offset = (if (daysDiff < 0) daysDiff + 7 else daysDiff)
        // 0x10204081 is binary 0b10000001000000100000010000001
        array(i) &= ~(0x10204081 << offset)
      }
      firstOfMonth = firstOfMonth.plusMonths(1)
      i += 1
    }
    // unset the bit associated with each holiday date
    val holidayIt = holidays.iterator()
    while (holidayIt.hasNext()) {
      val date = holidayIt.next()
      val index = (date.getYear() - startYear) * 12 + date.getMonthValue() - 1
      array(index) &= ~(1 << (date.getDayOfMonth() - 1))
    }
    // set the bit associated with each overriding working day
    val workingIt = workingDays.iterator()
    while (workingIt.hasNext()) {
      val date = workingIt.next()
      if (date.getYear() >= startYear && date.getYear() < endYearExclusive) {
        val index = (date.getYear() - startYear) * 12 + date.getMonthValue() - 1
        array(index) |= (1 << (date.getDayOfMonth() - 1))
      }
    }
    array
  }

