/**
 * An immutable holiday calendar implementation.
 *
 * A standard immutable implementation of `HolidayCalendar` that stores all
 * dates that are holidays, plus a list of weekend days.
 *
 * Internally, the class uses a range to determine the range of known holiday dates.
 * Beyond the range of known holiday dates, weekend days are used to determine business days.
 * Dates may be queried from year zero to year 10,000.
 *
 * Applications should refer to holidays using `HolidayCalendarId`.
 * The identifier must be resolved
 * to a `HolidayCalendar` before the holiday data methods can be accessed.
 * See `HolidayCalendarIds` for a standard set of identifiers available in `ReferenceData#standard()`.
 */
@BeanDefinition(builderScope = "private")
@SerialVersionUID(2L)
final class ImmutableHolidayCalendar private[date] (
    /**
     * The identifier, such as 'GBLO'.
     */
    @(PropertyDefinition @field)(validate = "notNull", overrideGet = true)
    private val id: HolidayCalendarId,
    /**
     * The set of weekend days.
     *
     * Each date that has a day-of-week matching one of these days is not a business day.
     */
    @(PropertyDefinition @field)(get = "")
    private val weekends: Int,
    /**
     * The start year.
     * Used as the base year for the lookup table.
     */
    @(PropertyDefinition @field)(get = "")
    private val startYear: Int,
    /**
     * The lookup table, where each item represents a month from January of startYear onwards.
     * Bits 0 to 31 are used for each day-of-month, where 0 is a holiday and 1 is a business day.
     * Trailing bits are set to 0 so they act as holidays, avoiding month length logic.
     */
    @(PropertyDefinition @field)(validate = "notNull", get = "")
    private val lookup: Array[Int],
    flag: Boolean)
  extends HolidayCalendar with ImmutableBean with Serializable {
  // optimized implementation of HolidayCalendar
  // uses an int array where each int represents a month
  // each bit within the int represents a date, where 0 is a holiday and 1 is a business day
  // (most logic involves finding business days, finding 1 is easier than finding 0
  // when using Integer.numberOfTrailingZeros and Integer.numberOfLeadingZeros)
  // benchmarking showed nextOrSame() and previousOrSame() do not need to be overridden
  // out-of-range and weekend-only (used in testing) are handled using exceptions to fast-path the common case

  // the primary constructor creates an instance, not cloning the lookup
  ArgChecker.notNull(id, "id")
  ArgChecker.notNull(lookup, "lookup")

  //------------------------- AUTOGENERATED START -------------------------
  private def this(
      id: HolidayCalendarId,
      weekends: Int,
      startYear: Int,
      lookup: Array[Int]) = {
    this(
        { JodaBeanUtils.notNull(id, "id"); id },
        weekends,
        startYear,
        { JodaBeanUtils.notNull(lookup, "lookup"); lookup.clone() },
        false)
  }
  //-------------------------- AUTOGENERATED END --------------------------

  //-------------------------------------------------------------------------
  // writes the binary format
  @throws[IOException]
  private[date] def writeExternal(out: DataOutput): Unit = {
    out.writeUTF(id.getName())
    out.writeShort(weekends)  // using short rather than byte helps align data with 4 char identifiers
    out.writeShort(startYear)
    out.writeShort(lookup.length)
    var i = 0
    while (i < lookup.length) {
      out.writeInt(lookup(i))
      i += 1
    }
  }

  //-------------------------------------------------------------------------
  // returns the holidays as a set
  @VisibleForTesting
  private[date] def getHolidays(): ImmutableSortedSet[LocalDate] = {
    getHolidaysAndWorkingDays().getFirst()
  }

  // returns the weekend days as a set
  @VisibleForTesting
  private[date] def getWeekendDays(): ImmutableSet[DayOfWeek] = {
    Stream.of(DayOfWeek.values()*)
        .filter(dow => (weekends & (1 << dow.ordinal())) != 0)
        .collect(Guavate.toImmutableSet[DayOfWeek]())
  }

  // returns the working day overrides as a set
  @VisibleForTesting
  private[date] def getWorkingDays(): ImmutableSortedSet[LocalDate] = {
    getHolidaysAndWorkingDays().getSecond()
  }

  // returns the working day overrides as a set
  private def getHolidaysAndWorkingDays(): Pair[ImmutableSortedSet[LocalDate], ImmutableSortedSet[LocalDate]] = {
    if (startYear == 0) {
      return Pair.of(ImmutableSortedSet.of[LocalDate](), ImmutableSortedSet.of[LocalDate]())
    }
    val holidays: ImmutableSortedSet.Builder[LocalDate] = ImmutableSortedSet.naturalOrder[LocalDate]()
    val workingDays: ImmutableSortedSet.Builder[LocalDate] = ImmutableSortedSet.naturalOrder[LocalDate]()
    var firstOfMonth = LocalDate.of(startYear, 1, 1)
    var i = 0
    while (i < lookup.length) {
      val monthData = lookup(i)
      val monthLen = firstOfMonth.lengthOfMonth()
      var dow0 = firstOfMonth.getDayOfWeek().ordinal()
      var bit = 1
      var j = 0
      while (j < monthLen) {
        // if it is a holiday and not a weekend, then add the date
        if ((monthData & bit) == 0 && (weekends & (1 << dow0)) == 0) {
          holidays.add(firstOfMonth.withDayOfMonth(j + 1))
        }
        // if it is a working day and a weekend, then add the date
        if ((monthData & bit) != 0 && (weekends & (1 << dow0)) != 0) {
          workingDays.add(firstOfMonth.withDayOfMonth(j + 1))
        }
        dow0 = (dow0 + 1) % 7
        bit <<= 1
        j += 1
      }
      firstOfMonth = firstOfMonth.plusMonths(1)
      i += 1
    }
    Pair.of(holidays.build(), workingDays.build())
  }

  //-------------------------------------------------------------------------
  override def isHoliday(date: LocalDate): Boolean = {
    try {
      // find data for month
      val index = (date.getYear() - startYear) * 12 + date.getMonthValue() - 1
      // check if bit is 1 at zero-based day-of-month
      (lookup(index) & (1 << (date.getDayOfMonth() - 1))) == 0

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        isHolidayOutOfRange(date)
    }
  }

  // pulled out to aid hotspot inlining
  private def isHolidayOutOfRange(date: LocalDate): Boolean = {
    if (date.getYear() >= 0 && date.getYear() < 10000) {
      return (weekends & (1 << date.getDayOfWeek().ordinal())) != 0
    }
    throw new IllegalArgumentException("Date is outside the accepted range (year 0000 to 10,000): " + date)
  }

  //-------------------------------------------------------------------------
  override def shift(date: LocalDate, amount: Int): LocalDate = {
    try {
      if (amount > 0) {
        // day-of-month: minus one for zero-based day-of-month, plus one to start from next day
        shiftNext(date.getYear(), date.getMonthValue(), date.getDayOfMonth(), amount)
      } else if (amount < 0) {
        // day-of-month: minus one to start from previous day
        shiftPrev(date.getYear(), date.getMonthValue(), date.getDayOfMonth() - 1, amount)
      } else {
        date
      }

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        shiftOutOfRange(date, amount)
    }
  }

  // pulled out to aid hotspot inlining
  private def shiftOutOfRange(date: LocalDate, amount: Int): LocalDate = {
    if (date.getYear() >= 0 && date.getYear() < 10000) {
      return super[HolidayCalendar].shift(date, amount)
    }
    throw new IllegalArgumentException("Date is outside the accepted range (year 0000 to 10,000): " + date)
  }

  //-------------------------------------------------------------------------
  override def next(date: LocalDate): LocalDate = {
    try {
      // day-of-month: minus one for zero-based day-of-month, plus one to start from next day
      shiftNext(date.getYear(), date.getMonthValue(), date.getDayOfMonth(), 1)

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        super[HolidayCalendar].next(date)
    }
  }

  // shift to a later working day, following nextOrSame semantics
  // input day-of-month is zero-based
  private def shiftNext(baseYear: Int, baseMonth: Int, baseDom0: Int, amount: Int): LocalDate = {
    // find data for month
    val index = (baseYear - startYear) * 12 + baseMonth - 1
    val monthData = lookup(index)
    // loop around amount, the number of days to shift by
    // use domOffset to keep track of day-of-month
    var domOffset = baseDom0
    var amt = amount
    while (amt > 0) {
      // shift to move the target day-of-month into bit-0, removing earlier days
      val shifted = monthData >>> domOffset
      // recurse to next month if no more business days in the month
      if (shifted == 0) {
        return if (baseMonth == 12) shiftNext(baseYear + 1, 1, 0, amt) else shiftNext(baseYear, baseMonth + 1, 0, amt)
      }
      // find least significant bit, which is next business day
      // use JDK numberOfTrailingZeros() method which is mapped to a fast intrinsic
      domOffset += (Integer.numberOfTrailingZeros(shifted) + 1)
      amt -= 1
    }
    LocalDate.of(baseYear, baseMonth, domOffset)
  }

  //-------------------------------------------------------------------------
  override def previous(date: LocalDate): LocalDate = {
    try {
      // day-of-month: minus one to start from previous day
      shiftPrev(date.getYear(), date.getMonthValue(), date.getDayOfMonth() - 1, -1)

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        previousOutOfRange(date)
    }
  }

  // shift to an earlier working day, following previousOrSame semantics
  // input day-of-month is one-based and may be zero or negative
  private def shiftPrev(baseYear: Int, baseMonth: Int, baseDom: Int, amount: Int): LocalDate = {
    // find data for month
    val index = (baseYear - startYear) * 12 + baseMonth - 1
    val monthData = lookup(index)
    // loop around amount, the number of days to shift by
    // use domOffset to keep track of day-of-month
    var domOffset = baseDom
    var amt = amount
    while (amt < 0) {
      // shift to move the target day-of-month into bit-31, removing later days
      val shifted = (monthData << (32 - domOffset))
      // recurse to previous month if no more business days in the month
      if (shifted == 0 || domOffset <= 0) {
        return if (baseMonth == 1) shiftPrev(baseYear - 1, 12, 31, amt) else shiftPrev(baseYear, baseMonth - 1, 31, amt)
      }
      // find most significant bit, which is previous business day
      // use JDK numberOfLeadingZeros() method which is mapped to a fast intrinsic
      domOffset -= (Integer.numberOfLeadingZeros(shifted) + 1)
      amt += 1
    }
    LocalDate.of(baseYear, baseMonth, domOffset + 1)
  }

  // pulled out to aid hotspot inlining
  private def previousOutOfRange(date: LocalDate): LocalDate = {
    if (date.getYear() >= 0 && date.getYear() < 10000) {
      return super[HolidayCalendar].previous(date)
    }
    throw new IllegalArgumentException("Date is outside the accepted range (year 0000 to 10,000): " + date)
  }

  //-------------------------------------------------------------------------
  override def nextSameOrLastInMonth(date: LocalDate): LocalDate = {
    try {
      // day-of-month: no alteration as method is one-based and same is valid
      shiftNextSameLast(date)

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        super[HolidayCalendar].nextSameOrLastInMonth(date)
    }
  }

  // shift to a later working day, following nextOrSame semantics
  // falling back to the last business day-of-month to avoid crossing a month boundary
  // input day-of-month is one-based
  private def shiftNextSameLast(baseDate: LocalDate): LocalDate = {
    val baseYear = baseDate.getYear()
    val baseMonth = baseDate.getMonthValue()
    val baseDom = baseDate.getDayOfMonth()
    // find data for month
    val index = (baseYear - startYear) * 12 + baseMonth - 1
    val monthData = lookup(index)
    // shift to move the target day-of-month into bit-0, removing earlier days
    val shifted = monthData >>> (baseDom - 1)
    // return last business day-of-month if no more business days in the month
    var dom = 0
    if (shifted == 0) {
      // need to find the most significant bit, which is the last business day
      // use JDK numberOfLeadingZeros() method which is mapped to a fast intrinsic
      val leading = Integer.numberOfLeadingZeros(monthData)
      dom = 32 - leading
    } else {
      // find least significant bit, which is the next/same business day
      // use JDK numberOfTrailingZeros() method which is mapped to a fast intrinsic
      dom = baseDom + Integer.numberOfTrailingZeros(shifted)
    }
    // only one call to LocalDate to aid inlining
    baseDate.withDayOfMonth(dom)
  }

  //-------------------------------------------------------------------------
  override def isLastBusinessDayOfMonth(date: LocalDate): Boolean = {
    try {
      // find data for month
      val index = (date.getYear() - startYear) * 12 + date.getMonthValue() - 1
      // shift right, leaving the input date as bit-0 and filling with 0 on the left
      // if the result is 1, which is all zeroes and a final 1 (...0001) then it is last business day of month
      (lookup(index) >>> (date.getDayOfMonth() - 1)) == 1

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        isLastBusinessDayOfMonthOutOfRange(date)
    }
  }

  // pulled out to aid hotspot inlining
  private def isLastBusinessDayOfMonthOutOfRange(date: LocalDate): Boolean = {
    if (date.getYear() >= 0 && date.getYear() < 10000) {
      return super[HolidayCalendar].isLastBusinessDayOfMonth(date)
    }
    throw new IllegalArgumentException("Date is outside the accepted range (year 0000 to 10,000): " + date)
  }

  //-------------------------------------------------------------------------
  override def lastBusinessDayOfMonth(date: LocalDate): LocalDate = {
    try {
      // find data for month
      val index = (date.getYear() - startYear) * 12 + date.getMonthValue() - 1
      // need to find the most significant bit, which is the last business day
      // use JDK numberOfLeadingZeros() method which is mapped to a fast intrinsic
      val leading = Integer.numberOfLeadingZeros(lookup(index))
      date.withDayOfMonth(32 - leading)

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        lastBusinessDayOfMonthOutOfRange(date)
    }
  }

  // pulled out to aid hotspot inlining
  private def lastBusinessDayOfMonthOutOfRange(date: LocalDate): LocalDate = {
    if (date.getYear() >= 0 && date.getYear() < 10000) {
      return super[HolidayCalendar].lastBusinessDayOfMonth(date)
    }
    throw new IllegalArgumentException("Date is outside the accepted range (year 0000 to 10,000): " + date)
  }

  //-------------------------------------------------------------------------
  override def daysBetween(startInclusive: LocalDate, endExclusive: LocalDate): Int = {
    ArgChecker.inOrderOrEqual(startInclusive, endExclusive, "startInclusive", "endExclusive")
    try {
      // find data for start and end month
      val startIndex = (startInclusive.getYear() - startYear) * 12 + startInclusive.getMonthValue() - 1
      val endIndex = (endExclusive.getYear() - startYear) * 12 + endExclusive.getMonthValue() - 1

      // count of first month = ones after day of month inclusive
      // e.g 4th day of month - want holidays from index 3 inclusive
      val start = Integer.bitCount(lookup(startIndex) >>> (startInclusive.getDayOfMonth() - 1))
      // count of last month = ones before day of month exclusive == total for month - ones after end inclusive
      val missingEnd = Integer.bitCount(lookup(endIndex) >>> (endExclusive.getDayOfMonth() - 1))
      if (startIndex == endIndex) {
        // same month - return holidays up to end exclusive
        start - missingEnd
      } else {
        val end = Integer.bitCount(lookup(endIndex)) - missingEnd
        // otherwise add start and end month counts, and sum months between
        var count = start + end
        var i = startIndex + 1
        while (i < endIndex) {
          count += Integer.bitCount(lookup(i))
          i += 1
        }
        count
      }

    } catch {
      case _: ArrayIndexOutOfBoundsException =>
        daysBetweenOutOfRange(startInclusive, endExclusive)
    }
  }

  // pulled out to aid hotspot inlining
  private def daysBetweenOutOfRange(startInclusive: LocalDate, endExclusive: LocalDate): Int = {
    if (startInclusive.getYear() >= 0 && startInclusive.getYear() < 10000 &&
        endExclusive.getYear() >= 0 && endExclusive.getYear() < 10000) {
      return super[HolidayCalendar].daysBetween(startInclusive, endExclusive)
    }
    throw new IllegalArgumentException(Messages.format(
        "Dates are outside the accepted range (year 0000 to 10,000): {}, {}",
        startInclusive, endExclusive))
  }

  //-------------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else {
      obj match {
        case other: ImmutableHolidayCalendar => id.equals(other.id)
        case _ => false
      }
    }
  }

  override def hashCode(): Int = {
    id.hashCode()
  }

  //-------------------------------------------------------------------------
  /**
   * Returns the name of the calendar.
   *
   * @return the descriptive string
   */
  override def toString(): String = {
    "HolidayCalendar[" + getName() + ']'
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): ImmutableHolidayCalendar.Meta = {
    ImmutableHolidayCalendar.Meta.INSTANCE
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the identifier, such as 'GBLO'.
   * @return the value of the property, not null
   */
  override def getId(): HolidayCalendarId = {
    id
  }

  //-------------------------- AUTOGENERATED END --------------------------
}

object ImmutableHolidayCalendar {

  /**
   * The deserializer, for compatibility.
   */
  @static final val DESERIALIZER: SerDeserializer = new ImmutableHolidayCalendarDeserializer()

  @static private val REGISTERED: Boolean = {
    MetaBean.register(ImmutableHolidayCalendar.Meta.INSTANCE)
    true
  }

  //-------------------------------------------------------------------------
  /**
   * Obtains an instance from a set of holiday dates and weekend days.
   *
   * The holiday dates will be extracted into a set with duplicates ignored.
   * The minimum supported date for query is the start of the year of the earliest holiday.
   * The maximum supported date for query is the end of the year of the latest holiday.
   *
   * The weekend days may both be the same.
   *
   * @param id  the identifier
   * @param holidays  the set of holiday dates
   * @param firstWeekendDay  the first weekend day
   * @param secondWeekendDay  the second weekend day, may be same as first
   * @return the holiday calendar
   */
  @static def of(
      id: HolidayCalendarId,
      holidays: java.lang.Iterable[LocalDate],
      firstWeekendDay: DayOfWeek,
      secondWeekendDay: DayOfWeek): ImmutableHolidayCalendar = {

    val weekendDays: ImmutableSet[DayOfWeek] = Sets.immutableEnumSet(firstWeekendDay, secondWeekendDay)
    of(id, ImmutableSortedSet.copyOf[LocalDate](holidays), weekendDays, ImmutableSet.of[LocalDate]())
  }

  /**
   * Obtains an instance from a set of holiday dates and weekend days.
   *
   * The holiday dates will be extracted into a set with duplicates ignored.
   * The minimum supported date for query is the start of the year of the earliest holiday.
   * The maximum supported date for query is the end of the year of the latest holiday.
   *
   * The weekend days may be empty, in which case the holiday dates should contain any weekends.
   *
   * @param id  the identifier
   * @param holidays  the set of holiday dates
   * @param weekendDays  the days that define the weekend, if empty then weekends are treated as business days
   * @return the holiday calendar
   */
  @static def of(
      id: HolidayCalendarId,
      holidays: java.lang.Iterable[LocalDate],
      weekendDays: java.lang.Iterable[DayOfWeek]): ImmutableHolidayCalendar = {

    of(id, ImmutableSortedSet.copyOf[LocalDate](holidays), Sets.immutableEnumSet(weekendDays), ImmutableSet.of[LocalDate]())
  }

  /**
   * Obtains an instance from a set of holiday dates and weekend days.
   *
   * The holiday dates will be extracted into a set with duplicates ignored.
   * The minimum supported date for query is the start of the year of the earliest holiday.
   * The maximum supported date for query is the end of the year of the latest holiday.
   *
   * The weekend days may be empty, in which case the holiday dates should contain any weekends.
   * The working days are processed last, changing holidays and weekends back to business days,
   * but only within the range of supported years.
   *
   * @param id  the identifier
   * @param holidays  the set of holiday dates
   * @param weekendDays  the days that define the weekend, if empty then weekends are treated as business days
   * @param workingDays  the working days that override holidays and weekends
   * @return the holiday calendar
   */
  @static def of(
      id: HolidayCalendarId,
      holidays: java.lang.Iterable[LocalDate],
      weekendDays: java.lang.Iterable[DayOfWeek],
      workingDays: java.lang.Iterable[LocalDate]): ImmutableHolidayCalendar = {

    of(
        id,
        ImmutableSortedSet.copyOf[LocalDate](holidays),
        Sets.immutableEnumSet(weekendDays),
        ArgChecker.notNull(workingDays, "workingDays"))
  }

  /**
   * Obtains a combined holiday calendar instance.
   *
   * This combines the two input calendars.
   * It is intended for up-front occasional use rather than continuous use, as it can be relatively slow.
   *
   * @param cal1  the first calendar
   * @param cal2  the second calendar
   * @return the combined calendar
   */
  def combined(cal1: ImmutableHolidayCalendar, cal2: ImmutableHolidayCalendar): ImmutableHolidayCalendar = {
    // do not override combinedWith(), as this is too slow
    if (cal1 eq cal2) {
      return ArgChecker.notNull(cal1, "cal1")
    }
    val newId = cal1.id.combinedWith(cal2.id)

    // use slow version if lookup arrays do not overlap
    val endYear1 = cal1.startYear + cal1.lookup.length / 12
    val endYear2 = cal2.startYear + cal2.lookup.length / 12
    if (endYear1 < cal2.startYear || endYear2 < cal1.startYear) {
      val holsWork1 = cal1.getHolidaysAndWorkingDays()
      val holsWork2 = cal2.getHolidaysAndWorkingDays()
      val newHolidays: ImmutableSortedSet[LocalDate] =
        ImmutableSortedSet.copyOf[LocalDate](Iterables.concat[LocalDate](holsWork1.getFirst(), holsWork2.getFirst()))
      val newWeekends: ImmutableSet[DayOfWeek] =
        ImmutableSet.copyOf[DayOfWeek](Iterables.concat[DayOfWeek](cal1.getWeekendDays(), cal2.getWeekendDays()))
      val newWorkingDays: ImmutableSet[LocalDate] =
        ImmutableSet.copyOf[LocalDate](Iterables.concat[LocalDate](holsWork1.getSecond(), holsWork2.getSecond()))
      return of(newId, newHolidays, newWeekends, newWorkingDays)
    }

    // merge calendars using bitwise operations
    // figure out which has the lower start year and use that as the base
    val cal1Lower = cal1.startYear <= cal2.startYear
    val lookup1 = if (cal1Lower) cal1.lookup else cal2.lookup
    val lookup2 = if (cal1Lower) cal2.lookup else cal1.lookup
    val newStartYear = if (cal1Lower) cal1.startYear else cal2.startYear
    val otherStartYear = if (cal1Lower) cal2.startYear else cal1.startYear
    // copy base array and map data from the other on top
    val newSize = Math.max(lookup1.length, lookup2.length + (otherStartYear - newStartYear) * 12)
    val offset = (otherStartYear - newStartYear) * 12
    val newLookup = Arrays.copyOf(lookup1, newSize)
    var i = 0
    while (i < lookup2.length) {
      newLookup(i + offset) &= lookup2(i) // use & because 1 = business day (not holiday)
      i += 1
    }
    val newWeekends = cal1.weekends | cal2.weekends // use | because 1 = weekend day
    new ImmutableHolidayCalendar(newId, newWeekends, newStartYear, newLookup, false)
  }

  // creates an instance calculating the supported range
  @static private[date] def of(
      id: HolidayCalendarId,
      holidays: SortedSet[LocalDate],
      weekendDays: Set[DayOfWeek],
      workingDays: java.lang.Iterable[LocalDate]): ImmutableHolidayCalendar = {

    ArgChecker.notNull(id, "id")
    val weekends = weekendDays.stream().mapToInt(dow => 1 << (dow.getValue() - 1)).sum()
    // initial case where no holiday dates are specified
    var startYear = 0
    var lookup = new Array[Int](0)
    if (!holidays.isEmpty()) {
      // normal case where holidays are specified
      startYear = holidays.first().getYear()
      val endYearExclusive = holidays.last().getYear() + 1
      lookup = buildLookupArray(holidays, weekendDays, startYear, endYearExclusive, workingDays)
    }
    new ImmutableHolidayCalendar(id, weekends, startYear, lookup)
  }

  // create and populate the int[] lookup
  // use 1 for business days and 0 for holidays
  private def buildLookupArray(
      holidays: java.lang.Iterable[LocalDate],
      weekendDays: java.lang.Iterable[DayOfWeek],
      startYear: Int,
      endYearExclusive: Int,
      workingDays: java.lang.Iterable[LocalDate]): Array[Int] = {

    // array that has one entry for each month
