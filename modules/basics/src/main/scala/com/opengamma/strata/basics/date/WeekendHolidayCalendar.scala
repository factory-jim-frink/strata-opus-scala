    /**
     * The identifier.
     */
    @(PropertyDefinition @field)(validate = "notNull", overrideGet = true)
    private val id: HolidayCalendarId,
    /**
     * The first weekend day.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val day1: DayOfWeek,
    /**
     * The second weekend day.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val day2: DayOfWeek)
  extends HolidayCalendar with ImmutableBean with Serializable {
  // methods are overridden from default implementations to gain performance

  JodaBeanUtils.notNull(id, "id")
