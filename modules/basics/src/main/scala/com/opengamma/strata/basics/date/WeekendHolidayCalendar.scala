      throw new InvalidObjectException("Invalid WeekendHolidayCalendar identifier")
    }
  }

  //-------------------------------------------------------------------------
  override def isHoliday(date: LocalDate): Boolean = {
    val dow = date.getDayOfWeek()
    (dow eq day1) || (dow eq day2)
  }

