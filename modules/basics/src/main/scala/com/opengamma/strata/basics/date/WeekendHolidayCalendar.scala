  JodaBeanUtils.notNull(day2, "day2")

  // resolve after deserialization
  @throws[InvalidObjectException]
  private def readResolve(): Object = {
    if (id eq HolidayCalendarIds.SAT_SUN) {
      WeekendHolidayCalendar.SAT_SUN
