/**
 * An adjustable date.
 *
 * This class combines an unadjusted date and the business day adjustment necessary to adjust it.
 * Calling the `adjusted(ReferenceData)` method will return the adjusted date.
 */
@BeanDefinition(builderScope = "private")
@SerialVersionUID(1L)
final class AdjustableDate private (
    /**
     * The unadjusted date.
     *
     * This date may be a non-business day.
     * The business day adjustment is used to ensure it is a valid business day.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val unadjusted: LocalDate,
    /**
     * The business day adjustment that is to be applied to the unadjusted date.
     *
     * This is used to adjust the date if it is not a business day.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val adjustment: BusinessDayAdjustment)
  extends ImmutableBean with Serializable {

  JodaBeanUtils.notNull(unadjusted, "unadjusted")
  JodaBeanUtils.notNull(adjustment, "adjustment")

  //-------------------------------------------------------------------------
  /**
   * Adjusts the date using the business day adjustment.
   *
   * This returns the adjusted date, calculated by applying the business day
   * adjustment to the unadjusted date.
   *
   * @param refData  the reference data to use
   * @return the adjusted date
   */
  def adjusted(refData: ReferenceData): LocalDate = {
    adjustment.adjust(unadjusted, refData)
  }

  //-------------------------------------------------------------------------
  /**
   * Returns a string describing the adjustable date.
   *
   * @return the descriptive string
   */
  override def toString(): String = {
    if (adjustment.equals(BusinessDayAdjustment.NONE)) {
      unadjusted.toString()
    } else {
      new java.lang.StringBuilder(64)
          .append(unadjusted)
          .append(" adjusted by ")
          .append(adjustment).toString()
    }
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): AdjustableDate.Meta = {
    AdjustableDate.Meta.INSTANCE
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the unadjusted date.
   *
   * This date may be a non-business day.
   * The business day adjustment is used to ensure it is a valid business day.
   * @return the value of the property, not null
   */
  def getUnadjusted(): LocalDate = {
    unadjusted
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the business day adjustment that is to be applied to the unadjusted date.
   *
   * This is used to adjust the date if it is not a business day.
   * @return the value of the property, not null
   */
  def getAdjustment(): BusinessDayAdjustment = {
    adjustment
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else if (obj != null && (obj.getClass() eq this.getClass())) {
      val other = obj.asInstanceOf[AdjustableDate]
      JodaBeanUtils.equal(unadjusted, other.unadjusted) &&
          JodaBeanUtils.equal(adjustment, other.adjustment)
    } else {
      false
    }
  }

  override def hashCode(): Int = {
    var hash = getClass().hashCode()
    hash = hash * 31 + JodaBeanUtils.hashCode(unadjusted)
    hash = hash * 31 + JodaBeanUtils.hashCode(adjustment)
    hash
  }

