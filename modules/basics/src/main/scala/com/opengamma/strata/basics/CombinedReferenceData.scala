    refData1
  }

  //-----------------------------------------------------------------------
  /**
   * Gets the second set of reference data.
   * @return the value of the property, not null
   */
  def getRefData2(): ReferenceData = {
    refData2
  }

  //-----------------------------------------------------------------------
  override def equals(obj: Any): Boolean = {
    if (obj.asInstanceOf[AnyRef] eq this) {
      true
    } else if (obj != null && (obj.getClass() eq this.getClass())) {
      val other = obj.asInstanceOf[CombinedReferenceData]
      JodaBeanUtils.equal(refData1, other.refData1) &&
          JodaBeanUtils.equal(refData2, other.refData2)
    } else {
      false
    }
  }

  override def hashCode(): Int = {
    var hash = getClass().hashCode()
    hash = hash * 31 + JodaBeanUtils.hashCode(refData1)
    hash = hash * 31 + JodaBeanUtils.hashCode(refData2)
