    @(PropertyDefinition @field)(validate = "notNull")
    private val refData1: ReferenceData,
    /**
     * The second set of reference data.
     */
    @(PropertyDefinition @field)(validate = "notNull")
    private val refData2: ReferenceData)
  extends ReferenceData with ImmutableBean with Serializable {

  JodaBeanUtils.notNull(refData1, "refData1")
  JodaBeanUtils.notNull(refData2, "refData2")

  //-------------------------------------------------------------------------
  override def containsValue(id: ReferenceDataId[?]): Boolean = {
    refData1.containsValue(id) || refData2.containsValue(id)
  }

  override def queryValueOrNull[T](id: ReferenceDataId[T]): T = {
    val value1: T = refData1.queryValueOrNull(id)
    if (value1 != null) value1 else refData2.queryValueOrNull(id)
  }

  //------------------------- AUTOGENERATED START -------------------------
  override def metaBean(): TypedMetaBean[CombinedReferenceData] = {
    CombinedReferenceData.META_BEAN
  }

  //-----------------------------------------------------------------------
